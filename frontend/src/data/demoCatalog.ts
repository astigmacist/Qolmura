export function getDemoProducts(params: URLSearchParams): PaginatedProducts {
  const search = (params.get("search") ?? "").trim().toLocaleLowerCase()
  const categorySlug = params.get("category__slug") ?? ""
  const ordering = params.get("ordering") ?? "-created_at"

  let results = demoProducts.filter((product) => {
    if (categorySlug && product.category.slug !== categorySlug) return false
    if (!search) return true
    const haystack = [
      product.name_kk,
      product.name_ru,
      product.description_kk,
      product.description_ru,
      product.artisan.shop_name,
      product.artisan.city,
    ].join(" ").toLocaleLowerCase()
    return haystack.includes(search)
  })

  if (ordering === "price" || ordering === "-price") {
    const direction = ordering === "price" ? 1 : -1
    results = [...results].sort((a, b) => (Number(a.price) - Number(b.price)) * direction)
  }

  return { count: results.length, next: null, previous: null, results }
}
